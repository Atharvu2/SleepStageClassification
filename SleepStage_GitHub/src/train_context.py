"""Evaluate classical classifiers with context-aware EEG features using LOSO CV.

Input files are generated by src/build_dataset.py:
  results/features.npz
  results/epoch_metadata.csv

The context window is built from retained labelled epochs within each recording.
Because unlabelled epochs are dropped upstream, adjacent retained rows are not
necessarily consecutive 30-second epochs in the original signal.
"""
from pathlib import Path
import json
import time
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import LeaveOneGroupOut
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import RandomForestClassifier, ExtraTreesClassifier
from sklearn.svm import SVC
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import (
    accuracy_score, f1_score, cohen_kappa_score, classification_report,
    confusion_matrix, ConfusionMatrixDisplay,
)
from sklearn.utils.class_weight import compute_sample_weight
from xgboost import XGBClassifier

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results"
FIG = ROOT / "figures"
NAMES = ["Wake", "N1", "N2", "N3", "REM"]
SHIFTS = (-4, -3, -2, -1, 1, 2, 3, 4)
POWER_COLS = [11, 13, 15, 17, 19]


def build_context_features(X, recording, shifts=SHIFTS, log_power=True):
    """Return central-epoch features concatenated with shifted features per recording."""
    X = np.asarray(X, dtype=np.float64).copy()
    if log_power:
        for col in POWER_COLS:
            X[:, col] = np.log(np.maximum(X[:, col], 0) + 1e-12)
    parts = [X]
    recording = np.asarray(recording)
    for shift in shifts:
        shifted = np.empty_like(X)
        for rec in np.unique(recording):
            idx = np.flatnonzero(recording == rec)
            positions = np.clip(np.arange(len(idx)) + shift, 0, len(idx) - 1)
            shifted[idx] = X[idx[positions]]
        parts.append(shifted)
    return np.hstack(parts)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    data = np.load(OUT / "features.npz", allow_pickle=True)
    X, y, groups = data["X"], data["y"].astype(int), data["groups"].astype(str)
    metadata = pd.read_csv(OUT / "epoch_metadata.csv")
    if not np.array_equal(metadata["label"].to_numpy(), y):
        raise ValueError("epoch_metadata.csv labels do not align with features.npz")
    recording = metadata["recording"].astype(str).to_numpy()
    F = build_context_features(X, recording)

    models = {
        "RandomForest": RandomForestClassifier(
            n_estimators=300, min_samples_leaf=2, class_weight="balanced_subsample",
            n_jobs=-1, random_state=42),
        "ExtraTrees": ExtraTreesClassifier(
            n_estimators=300, min_samples_leaf=2, class_weight="balanced",
            n_jobs=-1, random_state=42),
        "SVM_RBF": make_pipeline(StandardScaler(), SVC(C=3, class_weight="balanced")),
        "KNN": make_pipeline(StandardScaler(), KNeighborsClassifier(
            n_neighbors=9, weights="distance", n_jobs=-1)),
        "XGBoost": XGBClassifier(
            n_estimators=300, max_depth=4, learning_rate=0.05, subsample=0.8,
            colsample_bytree=0.7, tree_method="hist", n_jobs=-1,
            random_state=42, eval_metric="mlogloss"),
    }

    summary_rows, fold_summary, report_by_model = [], {}, {}
    for name, model in models.items():
        y_true_all, y_pred_all, subject_all = [], [], []
        folds = []
        started = time.time()
        for fold, (train_idx, test_idx) in enumerate(
                LeaveOneGroupOut().split(F, y, groups), start=1):
            if name == "XGBoost":
                model.fit(F[train_idx], y[train_idx],
                          sample_weight=compute_sample_weight("balanced", y[train_idx]))
            else:
                model.fit(F[train_idx], y[train_idx])
            pred = model.predict(F[test_idx]).astype(int)
            truth = y[test_idx].astype(int)
            held_out = str(groups[test_idx][0])
            y_true_all.extend(truth.tolist())
            y_pred_all.extend(pred.tolist())
            subject_all.extend(groups[test_idx].tolist())
            folds.append({
                "fold": fold, "held_out_subject": held_out,
                "n_test_epochs": int(len(test_idx)),
                "accuracy": float(accuracy_score(truth, pred)),
                "macro_f1": float(f1_score(truth, pred, average="macro", zero_division=0)),
                "weighted_f1": float(f1_score(truth, pred, average="weighted", zero_division=0)),
                "cohen_kappa": float(cohen_kappa_score(truth, pred)),
            })
        elapsed = round(time.time() - started, 1)
        yt, yp = np.asarray(y_true_all), np.asarray(y_pred_all)
        report = classification_report(yt, yp, labels=range(5), target_names=NAMES,
                                       output_dict=True, zero_division=0)
        report_by_model[name] = report
        fold_summary[name] = folds
        summary_rows.append({
            "model": name,
            "accuracy": float(accuracy_score(yt, yp)),
            "macro_f1": float(f1_score(yt, yp, average="macro", zero_division=0)),
            "weighted_f1": float(f1_score(yt, yp, average="weighted", zero_division=0)),
            "cohen_kappa": float(cohen_kappa_score(yt, yp)),
            "seconds": elapsed,
        })
        pd.DataFrame({"subject": subject_all, "y_true": yt, "y_pred": yp}).to_csv(
            OUT / f"predictions_{name}_context.csv", index=False)
        cm = confusion_matrix(yt, yp, labels=range(5))
        pd.DataFrame(cm, index=NAMES, columns=NAMES).to_csv(
            OUT / f"confusion_matrix_{name}_context.csv", index_label="actual")
        disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=NAMES)
        fig, ax = plt.subplots(figsize=(6.5, 5.5))
        disp.plot(ax=ax, cmap="Blues", values_format="d", colorbar=False)
        ax.set_title(f"{name}: Context-aware LOSO confusion matrix")
        fig.tight_layout()
        fig.savefig(FIG / f"confusion_{name}_context.png", dpi=300, bbox_inches="tight")
        plt.close(fig)
        print(f"{name}: accuracy={accuracy_score(yt, yp):.4f}, "
              f"macro-F1={f1_score(yt, yp, average='macro'):.4f}, "
              f"kappa={cohen_kappa_score(yt, yp):.4f}; N1 recall={report['N1']['recall']:.3f}",
              flush=True)

    results = pd.DataFrame(summary_rows)
    results.to_csv(OUT / "model_comparison_context.csv", index=False)
    (OUT / "classification_reports_context.json").write_text(
        json.dumps(report_by_model, indent=2))
    (OUT / "fold_metrics_context.json").write_text(json.dumps(fold_summary, indent=2))

    ax = results.set_index("model")[["accuracy", "macro_f1", "weighted_f1"]].plot(
        kind="bar", figsize=(10, 5), ylim=(0, 1), rot=20)
    ax.set_ylabel("Score")
    ax.set_title("Context-aware model comparison (LOSO)")
    ax.grid(axis="y", linestyle=":", alpha=0.5)
    ax.legend(loc="lower right")
    plt.tight_layout()
    plt.savefig(FIG / "model_comparison_context.png", dpi=300, bbox_inches="tight")
    plt.close()


if __name__ == "__main__":
    main()
